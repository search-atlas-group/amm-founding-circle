#!/usr/bin/env python3
# SessionEnd async hook. Append one entry per session to _brain/sessions/YYYY-MM-DD.md.
# Plain markdown only — honors feedback-brain-md-only.
# Idempotent: appends, never overwrites. Safe to remove individual day files.

import json, os, sys, datetime
from pathlib import Path

BRAIN = Path(os.environ.get("HARNESS_BRAIN") or "/Users/eillacs/Desktop/Agentic/_brain")
SESSIONS_DIR = BRAIN / 'sessions'

try:
    payload = json.loads(sys.stdin.read() or '{}')
except Exception:
    payload = {}

if not BRAIN.is_dir():
    sys.exit(0)

SESSIONS_DIR.mkdir(exist_ok=True)
today = datetime.date.today().isoformat()
out_file = SESSIONS_DIR / f'{today}.md'

session_id = payload.get('session_id', 'unknown')
transcript = payload.get('transcript_path', '')
cwd = payload.get('cwd', '')

turns, chars = 0, 0
if transcript:
    p = Path(transcript)
    if p.exists():
        try:
            with p.open() as f:
                for line in f:
                    turns += 1
                    chars += len(line)
        except Exception:
            pass

if not out_file.exists():
    out_file.write_text(
        f'---\n'
        f'tags: [brain, sessions, log]\n'
        f'date: {today}\n'
        f'note: Auto-generated by obsidian-session-capture.py — one entry per Claude Code session ending today.\n'
        f'---\n'
        f'# Session log {today}\n'
    )

now = datetime.datetime.now().strftime('%H:%M')
entry = (
    f'\n## {now} — session `{session_id[:8]}`\n'
    f'- cwd: `{cwd}`\n'
    f'- turns: {turns}\n'
    f'- transcript size: {chars:,} chars\n'
    f'- transcript: `{transcript}`\n'
)

with out_file.open('a') as f:
    f.write(entry)

sys.exit(0)
